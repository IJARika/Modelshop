	{
		assertm(texcoordIdx < texcoordCount, "texcoord out of range");
		assertm(data->texcoords, "texcoords was nullptr");

		return data->texcoords + (idx * texcoordCount) + texcoordIdx;
	}
	inline const IModelVertexBoneWeight* const GetWeight(const IModelVertex* const vertex, const uint32_t weight) const
	{
		assertm((vertex->GetWeightIndex() + weight) < weightCount, "weight out of range");
		assertm(weight < vertex->GetWeightCount(), "weight out of range");
		assertm(data->weights, "weights was nullptr");

		return data->weights + vertex->GetWeightIndex() + weight;
	}

