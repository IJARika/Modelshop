class IModelIKChain
{
public:
	IModelIKChain() = default;
	IModelIKChain(const r1::mstudioikchain_t* const pIKChain) : name(nullptr), unk(cos(45.0f))
	{
		assertm(pIKChain->numlinks == IKLINK_COUNT, "invalid ik chain");

		name = AllocStudioString(pIKChain->pszName());

		links[IKLINK_THIGH] = IModelIKLink(pIKChain->pLink(IKLINK_THIGH));
		links[IKLINK_KNEE] = IModelIKLink(pIKChain->pLink(IKLINK_KNEE));
		links[IKLINK_FOOT] = IModelIKLink(pIKChain->pLink(IKLINK_FOOT));
	}
	IModelIKChain(const r2::mstudioikchain_t* const pIKChain) : name(nullptr), unk(pIKChain->unk_10)
	{
		assertm(pIKChain->numlinks == IKLINK_COUNT, "invalid ik chain");

		name = AllocStudioString(pIKChain->pszName());

		links[IKLINK_THIGH] = IModelIKLink(pIKChain->pLink(IKLINK_THIGH));
		links[IKLINK_KNEE] = IModelIKLink(pIKChain->pLink(IKLINK_KNEE));
		links[IKLINK_FOOT] = IModelIKLink(pIKChain->pLink(IKLINK_FOOT));
	}
	~IModelIKChain()
	{
		FreeAllocArray(name);
	}

	enum LinkType_t
	{
		IKLINK_INVALID = -1,

		IKLINK_THIGH,
		IKLINK_KNEE,
		IKLINK_FOOT,

		IKLINK_COUNT
	};

	inline const char* const GetName() const { return name; }
	inline const float GetUnkAngle() const { return unk; }
	inline const IModelIKLink* const GetIKLink(const LinkType_t link) const
	{
		assertm(link < IKLINK_COUNT && link > IKLINK_INVALID, "invalid link index");
		return &links[link];
	}

	IModelIKChain& operator=(const IModelIKChain&&) = delete;
	IModelIKChain& operator=(IModelIKChain&& chain) noexcept
	{
		if (this != &chain)
		{
			memcpy_s(links, sizeof(links), chain.links, sizeof(chain.links));

			name = chain.name;
			unk = chain.unk;

			chain.name = nullptr;
		}

		return *this;
	}

private:
	char* name;
	float unk;

	// while this could be dynamic, it's hardcoded throughout all of source and reSource to assume it's 3
	// I'd imagine the original intent was to add more types with varied links, but that never happened
	IModelIKLink links[IKLINK_COUNT];
};


