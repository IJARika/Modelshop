	{
		if (this != &face)
		{
			indiceCount = face.indiceCount;

			memcpy_s(indices, indiceSize, face.indices, indiceSize);

			indiceExtra = face.indiceExtra;
			face.indiceExtra = nullptr;
		}

		return *this;
	}

