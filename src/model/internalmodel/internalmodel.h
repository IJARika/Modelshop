typedef uint64_t IModelAnimFlags_t;
enum eIModelAnimFlags : IModelAnimFlags_t
{
	IMODELANIM_FLAG_NONE,

	IMODELANIM_FLAG_LOOPING		= 0x0001,		// ending frame should be the same as the starting frame
	IMODELANIM_FLAG_SNAP		= 0x0002,		// do not interpolate between previous animation and this one
	IMODELANIM_FLAG_DELTA		= 0x0004,		// this sequence "adds" to the base sequences, not slerp blends
	IMODELANIM_FLAG_AUTOPLAY	= 0x0008,		// temporary flag that forces the sequence to always play
	IMODELANIM_FLAG_POST		= 0x0010,		// 
	IMODELANIM_FLAG_ALLZEROS	= 0x0020,		// this animation/sequence has no real animation data
	IMODELANIM_FLAG_FRAMEANIM	= 0x0040,		// animation is encoded as by frame x bone instead of RLE bone x frame
	IMODELANIM_FLAG_CYCLEPOSE	= 0x0080,		// cycle index is taken from a pose parameter index
	IMODELANIM_FLAG_REALTIME	= 0x0100,		// cycle index is taken from a real-time clock, not the animations cycle index
	IMODELANIM_FLAG_LOCAL		= 0x0200,		// sequence has a local context sequence
	IMODELANIM_FLAG_HIDDEN		= 0x0400,		// don't show in default selection views
	IMODELANIM_FLAG_OVERRIDE	= 0x0800,		// a forward declared sequence (empty)
	IMODELANIM_FLAG_ACTIVITY	= 0x1000,		// Has been updated at runtime to activity index
	IMODELANIM_FLAG_EVENT		= 0x2000,		// Has been updated at runtime to event index on server
	IMODELANIM_FLAG_WORLD		= 0x4000,		// sequence blends in worldspace
	IMODELANIM_FLAG_NOFORCELOOP		= 0x8000,	// do not force the animation loop
	IMODELANIM_FLAG_EVENT_CLIENT	= 0x10000,	// Has been updated at runtime to event index on client
	IMODELANIM_FLAG_HAS_SCALE		= 0x20000,	// only appears on anims with scale, used for quick lookup in ScaleBones, only reason this should be check is if there has been scale data parsed in, otherwise it is pointless (see ScaleBones checking if scale is 1.0f).
	IMODELANIM_FLAG_FRAMEMOVEMENT	= 0x40000,	// framemovements are only read if this flag is present
	IMODELANIM_FLAG_SINGLEFRAME		= 0x80000,	// this animation/sequence only has one frame of animation data
	IMODELANIM_FLAG_BPANIM			= 0x100000, // animation uses bluepoint's custom animation data
	IMODELANIM_FLAG_DATAPOINTANIM	= 0x200000, // animation uses a packing method which adjusts off of framepoints
	

	IMODELANIM_FLAG_SUPPGEST		= 0x10000000,	// (0x40) fills spot 0x40 (STUDIO_FRAMEANIM in r1, unused in r2), unknown, suppgest? set when suppgest is used on option line.
													// (0x40) 'suppress gestures' (emotes?) used in a lot of finishers so makes sense. there are sequences prefixed with 'gesture_', and activities with gesture in their name
	IMODELANIM_FLAG_HAS_ANIM		= 0x20000000,	// (0x20000) in apex STUDIO_HAS_SCALE only gets written on sequences, and this flag only gets written on animations		
	IMODELANIM_FLAG_UNK100000		= 0x40000000,	// (0x100000) in apex this flag seems to be used for idle sequences on reactive skins		

	// flags set on parsing, not from studio flags
	IMODELANIM_FLAG_MOVEMENTTRACK	= 0x1000000000,
};

class IModelAnimation
{
public:
	IModelAnimation() = default;
	IModelAnimation(const r1::studiohdr_t* const pHdr, const r1::mstudioanimdesc_t* const pAnimDesc, const StudioLooseData_t* const looseData);
	IModelAnimation(const r2::studiohdr_t* const pHdr, const r2::mstudioanimdesc_t* const pAnimDesc);
	~IModelAnimation();

	inline const char* const GetName() const { return name + IsSeqDeclared(); }
	inline const float GetFrameRate() const { return frameRate; }
	inline const int GetFrameCount() const { return frameCount; }
	inline const uint32_t GetFrameCount_UINT() const { return static_cast<uint32_t>(frameCount); }
	inline const IModelAnimFlags_t GetFlags() const { return flags; }

	inline const int GetMovementCount() const { return movementCount; }
	inline const IModelMovement* const GetMovement(const int index) const { return movements + index; }

	inline const int GetIKRuleCount() const { return ikRuleCount; }
	inline const IModelIKRule* const GetIKRule(const int index) const { return ikRules + index; }

	inline const int GetSectionFrames() const { return sectionFrames; }
	inline const int GetSectionCount() const { return sectionCount; }
	inline const int GetLocalSectionCount() const { return localSectionCount; }
	inline const int GetZeroFrameSpan() const { return zeroFrameSpan; }
	inline const int GetZeroFrameCount() const { return zeroFrameCount; }

	inline const float GetFrameOffset(const int frameIdx) const { return static_cast<float>((GetDuration() / GetFrameCount()) * frameIdx); } // offset in seconds to this frame
	inline const float GetDuration() const { return static_cast<float>(GetFrameCount() / GetFrameRate()); } // length in seconds of this animation

	inline const bool IsOverriden() const { return flags & IMODELANIM_FLAG_OVERRIDE; } // gets overwrote by external animation on load
	inline const bool IsSeqDeclared() const { return name[0] == '@'; }
	inline const bool IsNullName() const { return name[0] == '\0'; }

	inline const uint32_t GetBoneCount() const { return animTrackCount; }
	inline const IModelMovementTrack* GetMovementTrack() const { return movementTrack;  }
	inline const IModelAnimationTrack* GetAnimTrack(const int index) const { return animTracks + index; }
	inline const bool HasMovementTrack() const { return movementTrack && (flags & IMODELANIM_FLAG_MOVEMENTTRACK); }

	IModelAnimation& operator=(const IModelAnimation&& anim) = delete;
	IModelAnimation& operator=(IModelAnimation&& anim) noexcept
	{
		if (this != &anim)
		{
			memcpy_s(this, sizeof(IModelAnimation), &anim, sizeof(IModelAnimation));

			name = anim.name;

			movements = anim.movements;
			framemovement = anim.framemovement;
			ikRules = anim.ikRules;
			localHierarchies = anim.localHierarchies;

			animTracks = anim.animTracks;
			movementTrack = anim.movementTrack;

			anim.name = nullptr;

			anim.movements = nullptr;
			anim.framemovement = nullptr;
			anim.ikRules = nullptr;
			anim.localHierarchies = nullptr;

			anim.animTracks = nullptr;
			anim.movementTrack = nullptr;
		}

		return *this;
	}

private:
	char* name;

	float frameRate;
	int frameCount;

	IModelAnimFlags_t flags;

	int movementCount;
	IModelMovement* movements;
	IModelFrameMovement* framemovement;
	
	IModelIKRule* ikRules;
	int ikRuleCount;

	int localHierarchyCount;
	void* localHierarchies;

	int sectionFrames;		// max frames per section
	int sectionStallFrames;
	int16_t sectionCount;
	int16_t localSectionCount;	// one or more of the sections was stored locally
	int16_t zeroFrameSpan;
	int16_t zeroFrameCount;

	// parsed track data
	int animTrackCount;
	IModelAnimationTrack* animTracks;
	IModelMovementTrack* movementTrack; // on paper "framemovements" and normal source style "movements" should be properly extracted into this track.

	inline const float GetCycle(const int frame)
	{
		const float cycle = frameCount > 1 ? static_cast<float>(frame) / static_cast<float>(frameCount - 1) : 0.0f;
		assertm(isfinite(cycle), "cycle was nan");
		return cycle;
	}

	inline const bool HasStall() const { return sectionStallFrames > 0; }

	inline const int SectionCount(const bool useAnimData = false) const
	{
		const int useTrailSection = (flags & IMODELANIM_FLAG_DATAPOINTANIM) ? false : true; // rle anims have an extra section at the end, with only the last frame in full types (Quaternion48, Vector48, etc)
		const int useStallSection = HasStall();

		const int maxFrameIndex = (frameCount - sectionStallFrames - 1); // subtract to get the last frame index outside of stall

		const int sectionBase = (maxFrameIndex / sectionFrames); // basic section index
		const int sectionMaxIndex = sectionBase + useTrailSection + useStallSection; // max index of a section

		// [rika]: where we'd normally add one to get the count, in retail the first section omitted as it's expected to always be at offset 0 in animdata
		// [rika]: only retail animations will have this set, and it is not optional, if not set there is no animation data
		if (useAnimData)
			return sectionMaxIndex;

		return sectionMaxIndex + 1; // add one to make this max index a max count
	}
};

