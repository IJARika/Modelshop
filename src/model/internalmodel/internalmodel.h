	template<typename Indices, typename Bounds> void ModelUIPanel_ParseLocatingVertices(const Indices* const pUIIndices, const Bounds* const pUIBounds, const Vector* const parsedVertices, Vector* const vertexResult);
	template<typename Mesh, typename Bounds> void ModelUIPanel_ParseForQuad(const Vector* const vertexResult, const Vector* const parsedVertices, const Mesh* const pUIMesh, const Bounds* const pUIBounds, const int i);

