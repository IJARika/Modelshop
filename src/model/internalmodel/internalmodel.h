private:
	inline void SetFlags_R1(const int flags)
	{
		// should not have: STUDIOHDR_FLAGS_TRANSLUCENT_TWOPASS, STUDIOHDR_FLAGS_OBSOLETE, STUDIOHDR_FLAGS_CONSTANT_DIRECTIONAL_LIGHT_DOT, or STUDIOHDR_FLAGS_FLEXES_CONVERTED
		// STUDIOHDR_FLAGS_UNUSED_8 (STUDIOHDR_FLAGS_TRANSLUCENT_TWOPASS) set on models, but does not function in code. legacy studiomdl data?
		constexpr int maskDisabledFlags = (STUDIOHDR_FLAGS_UNUSED_2000 | STUDIOHDR_FLAGS_UNUSED_4000);
		assertm((flags & maskDisabledFlags) == false, "studio model had unused flag");

		sourceFlags = IMODELFLAGS_NONE;
		sourceFlags |= (flags & ~maskDisabledFlags);

		// no flags to adjust
	}

	inline void SetFlags_R2(const int flags)
	{
		// should not have: STUDIOHDR_FLAGS_TRANSLUCENT_TWOPASS, STUDIOHDR_FLAGS_OBSOLETE, STUDIOHDR_FLAGS_CONSTANT_DIRECTIONAL_LIGHT_DOT, or STUDIOHDR_FLAGS_FLEXES_CONVERTED
		constexpr int maskDisabledFlags = (STUDIOHDR_FLAGS_UNUSED_8 | STUDIOHDR_FLAGS_UNUSED_200 | STUDIOHDR_FLAGS_UNUSED_2000 | STUDIOHDR_FLAGS_UNUSED_4000);
		assertm((flags & maskDisabledFlags) == false, "studio model had unused flag");

		sourceFlags = IMODELFLAGS_NONE;
		sourceFlags |= (flags & ~maskDisabledFlags);

		// no flags to adjust
	}

	inline void SetFlags_R5(const int flags)
	{
		// flags previously known as: STUDIOHDR_FLAGS_TRANSLUCENT_TWOPASS, STUDIOHDR_FLAGS_OBSOLETE, STUDIOHDR_FLAGS_UNUSED, STUDIOHDR_FLAGS_CONSTANT_DIRECTIONAL_LIGHT_DOT, and STUDIOHDR_FLAGS_FLEXES_CONVERTED
		constexpr int maskDisabledFlags = (STUDIOHDR_FLAGS_UNK_8 | STUDIOHDR_FLAGS_UNUSED_200 | STUDIOHDR_FLAGS_UNK_400 | STUDIOHDR_FLAGS_UNK_2000 | STUDIOHDR_FLAGS_USES_EXTRA_BONE_WEIGHTS);

		sourceFlags = IMODELFLAGS_NONE;
		sourceFlags |= (flags & ~maskDisabledFlags);

		if (flags & STUDIOHDR_FLAGS_USES_EXTRA_BONE_WEIGHTS)
		{
			sourceFlags |= eIModelFlags::IMODEL_FLAG_USES_EXTRA_BONE_WEIGHTS;
		}

		if (flags & STUDIOHDR_FLAGS_UNK_8)
		{
			sourceFlags |= eIModelFlags::IMODEL_FLAG_UNK_8;
		}

		if (flags & STUDIOHDR_FLAGS_UNK_400)
		{
			sourceFlags |= eIModelFlags::IMODEL_FLAG_UNK_400;
		}

		if (flags & STUDIOHDR_FLAGS_UNK_2000)
		{
			sourceFlags |= eIModelFlags::IMODEL_FLAG_UNK_2000;
		}
	}
