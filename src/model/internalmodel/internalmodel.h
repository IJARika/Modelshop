	// a unique ordinal for this mesh
	int meshid;
	Vector center;

	IModelMeshData* data;

	uint64_t vertexCount : 24;
	uint64_t indiceCount : 20;
	uint64_t triangleCount : 20;
	uint32_t weightCount;

	uint16_t texcoordCount;
	uint16_t maxWeightsPerVert;

	inline void ParseSourceFlags(const IModelSourceFlags_t sourceFlags)
	{
		// bit shift?
		if (sourceFlags & IMODEL_FLAG_USES_VERTEX_COLOR)
		{
			flags |= eIModelMeshFlags::IMODELMESH_FLAG_COLOR;
		}

		if (sourceFlags & IMODEL_FLAG_USES_UV2)
		{
			flags |= eIModelMeshFlags::IMODELMESH_FLAG_TEXCOORD2;
			texcoordCount++;
		}
	}

	// for normal source
	inline void AddVertex(const OptimizedModel::Vertex_t* const pVert, const vvd::mstudiovertex_t* const pSrcVerts, const Vector4D* const pSrcTangs, const Color32* const pSrcColors, const Vector2D* const pSrcTexcoords,
		const OptimizedModel::BoneStateChangeHeader_t* const pBoneStates, const bool isHwSkinned)
	{
		const uint32_t vertexIndex = vertexCount;
		IModelVertex::ParseFromVTX(data->vertices + vertexIndex, vertexIndex, this, pVert, pSrcVerts, pSrcTangs, pSrcColors, pSrcTexcoords, pBoneStates, isHwSkinned);
		vertexCount++;
	}

	// for apex legends
	inline void AddVertex(const OptimizedModel::Vertex_t* const pVert, const vvd::mstudiovertex_t* const pSrcVerts, const Vector4D* const pSrcTangs, const Color32* const pSrcColors, const Vector2D* const pSrcTexcoords,
		const vvw::mstudioboneweightextra_t* const pSrcWeights)
	{
		const uint32_t vertexIndex = vertexCount;
		IModelVertex::ParseFromVTX(data->vertices + vertexIndex, vertexIndex, this, pVert, pSrcVerts, pSrcTangs, pSrcColors, pSrcTexcoords, pSrcWeights);
		vertexCount++;
	}

	// for ivps
	inline void AddVertex(const Vector* const pPos, const IModelVertexBoneWeight* const pWeight)
	{
		const uint32_t vertexIndex = vertexCount;
		IModelVertex::ParseFromIVPS(data->vertices + vertexIndex, this, pPos, pWeight);
		vertexCount++;
	}

	inline void AddIndice(const IModelFace& face)
	{
		data->indices[indiceCount] = IModelFace(face);
		indiceCount++;
	}

	inline void AddIndice(const IModelFaceIndice numIndices, const IModelFaceIndice* const pIndices)
	{
		data->indices[indiceCount] = IModelFace(numIndices, pIndices);
		indiceCount++;
	}

	void ShrinkData()
	{
		data->ShrinkData(vertexCount, indiceCount, triangleCount, weightCount, texcoordCount, flags & IMODELMESH_FLAG_COLOR);
	}

	void FromValveVertex(const OptimizedModel::MeshHeader_t* const pVertexMesh, const uint32_t lod, const int baseVertexOffset, const int studioVertCount, const bool isApex,
		const vvd::vertexFileHeader_t* const pVVD, const vvc::vertexColorFileHeader_t* const pVVC, const vvw::vertexBoneWeightsExtraFileHeader_t* const pVVW);

	const int FromIVPSNode(const ivps::compactledgenode_t* const pNode, uint32_t& maxVertexIndex);

